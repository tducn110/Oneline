import type { BridgeLevel, Difficulty } from "../types";

type N = [string, number, number]; // id, x, y (normalized 0..1)
type E = [string, string]; // from, to

/** Build a level; edge ids are assigned automatically as e1, e2, ... */
function mk(
  id: number,
  name: string,
  difficulty: Difficulty,
  nodes: N[],
  edges: E[],
  startNodeId?: string
): BridgeLevel {
  return {
    id,
    name,
    difficulty,
    nodes: nodes.map(([nid, x, y]) => ({ id: nid, x, y })),
    edges: edges.map(([from, to], i) => ({ id: `l${id}e${i + 1}`, from, to })),
    startNodeId,
  };
}

